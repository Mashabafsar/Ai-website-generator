/**
 * Turns an assembled site + blueprint into a complete, hostable project: static
 * HTML pages plus README, deploy config, and machine-readable data. Shared by
 * the GitHub Repository Agent and the ZIP Export Agent.
 */
export async function generateProjectFiles(params: {
  businessName: string;
  blueprint: WebsiteBlueprint;
  site: AssembledSite;
}): Promise<ProjectFile[]> {
  const { businessName, blueprint, site } = params;
  const name = slugify(businessName);

  const files: ProjectFile[] = [];

  const html = renderSiteToFiles(site);
  for (const [filePath, content] of Object.entries(html)) {
    files.push({ path: filePath, content });
  }

  // Include user-uploaded images and any design assets the layout falls back to,
  // so ZIP / GitHub sites stay self-contained.
  for (const rel of [...collectUploadPaths(blueprint), ...designAssetPaths(site)]) {
    try {
      const abs = path.join(process.cwd(), "public", rel);
      const buf = await readFile(abs);
      files.push({ path: rel, content: buf });
    } catch {
      // Skip missing assets rather than failing the whole export.
    }
  }

  files.push({
    path: "site.json",
    content: JSON.stringify(site, null, 2),
  });
  files.push({
    path: "blueprint.json",
    content: JSON.stringify(blueprint, null, 2),
  });

  files.push({
    path: "vercel.json",
    content: JSON.stringify({ cleanUrls: true, trailingSlash: false }, null, 2),
  });

  files.push({
    path: ".gitignore",
    content: ["node_modules", ".DS_Store", ".env", ".env.local", ""].join("\n"),
  });

  files.push({
    path: "package.json",
    content: JSON.stringify(
      {
        name: `${name}-website`,
        version: "1.0.0",
        private: true,
        description: `Website for ${businessName}, generated by Agency Partner Interactive.`,
        scripts: {
          start: "npx serve .",
        },
      },
      null,
      2
    ),
  });

  files.push({
    path: "README.md",
    content: readme(businessName),
  });

  files.push({
    path: ".env.example",
    content: "# This static site needs no secrets to run.\n",
  });

  return files;
}

function readme(businessName: string): string {
  return `# ${businessName}

This website was generated by **Agency Partner Interactive — AI Website Builder**.

## What's inside

- \`index.html\` and per-page \`*/index.html\` — the full static website (styled with Tailwind via CDN).
- \`uploads/\` — any images you uploaded in the editor (when present).
- \`site.json\` — the assembled section tree used to render the site.
- \`blueprint.json\` — the structured content blueprint the AI produced.
- \`vercel.json\` — static hosting configuration.

## Run locally

\`\`\`bash
npx serve .
\`\`\`

Then open the printed URL in your browser.

## Deploy

This is a static site. You can deploy it to any static host:

- Vercel / Netlify / Cloudflare Pages — drag-and-drop or connect the repo
- Any nginx / Apache / S3 static bucket

`;
}
